# おみくじ生成 (ローカル処理)
# ------------------------------
def generate_omikuji_local(mode):
    time.sleep(0.5)  # 演出用に少しスリープ
    
    weights = PRESETS.get(mode, PRESETS['normal'])
    
    # 重みに基づいて抽選
    keys = list(weights.keys())
    values = list(weights.values())
    
    result_type = random.choices(keys, weights=values, k=1)[0]
    
    # メッセージの選択
    messages = OMIKUJI_V2_DATA.get(result_type, ["今日も良い一日を！"])
    message = random.choice(messages)
    
    return {
        "result": result_type,
        "message": message,
        "timestamp_unix": int(time.time() * 1000)
    }

